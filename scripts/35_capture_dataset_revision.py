#!/usr/bin/env python3
"""Recover the HuggingFace dataset revision that PROVENANCE.md was missing.

The gap
-------
PROVENANCE.md carried `TODO(source): record the HuggingFace dataset revision
hash for the distribution these files came from. It was not captured at download
time and is needed for a complete provenance chain.`

It is recoverable after the fact, and the reasoning is worth stating because it
rests on an assumption rather than on a record.

The argument
------------
The dataset repository's metadata endpoint is readable without authentication
even though the data itself is gated. It reports the current head revision and
the date the repository was last modified. If the last modification predates our
download, then the revision we took is the one the endpoint reports now.

That is an inference, not a log entry. It would fail if the repository had been
changed and reverted, which `lastModified` would not distinguish. The file list
returned by the endpoint is compared against the eleven files we actually hold,
as a corroborating check.

Writes results/summaries/dataset_revision.md.
"""
from __future__ import annotations

import datetime as dt
import json
import pathlib
import re
import urllib.request

REPO_ID = "SageBio/mva-hackathon-2026-data"
API = f"https://huggingface.co/api/datasets/{REPO_ID}"
OUT = pathlib.Path("results/summaries/dataset_revision.md")
PROVENANCE = pathlib.Path("PROVENANCE.md")

#: When the files were downloaded, from the Phase 0 inventory date.
DOWNLOADED = dt.date(2026, 8, 31)


def main() -> None:
    req = urllib.request.Request(API, headers={"User-Agent": "mva-hackathon-2026"})
    with urllib.request.urlopen(req, timeout=60) as fh:
        d = json.load(fh)

    sha = d.get("sha")
    last = d.get("lastModified", "")
    last_date = dt.date.fromisoformat(last[:10]) if last[:10] else None
    files = sorted(s.get("rfilename") for s in d.get("siblings", []) if s.get("rfilename"))
    data_files = [f for f in files if not f.startswith(".") and f != "README.md"]

    # Scope to the input-file table only. Reading the whole document also picks
    # up the dbSNP file named in the upstream callset provenance, which is not
    # one of our inputs, and reports a mismatch that is a regex error rather
    # than a provenance problem.
    ours: list[str] = []
    if PROVENANCE.exists():
        text = PROVENANCE.read_text()
        start = text.find("<!-- BEGIN INPUT TABLE -->")
        end = text.find("<!-- END INPUT TABLE -->")
        table = text[start:end] if start != -1 and end != -1 else ""
        ours = sorted(set(re.findall(
            r"`([^`]+\.(?:vcf\.gz|vcf\.gz\.tbi|fastq\.gz|docx))`", table)))

    L: list[str] = []
    w = L.append
    w("# HuggingFace dataset revision, recovered\n")
    w(f"Generated by `scripts/35_capture_dataset_revision.py` on "
      f"{dt.date.today().isoformat()}.\n")
    w("| | |")
    w("|---|---|")
    w(f"| Repository | `{REPO_ID}` |")
    w(f"| Head revision | `{sha}` |")
    w(f"| Repository last modified | {last} |")
    w(f"| Our files downloaded | {DOWNLOADED.isoformat()} |")
    w(f"| Gated | {d.get('gated')} |")
    w("")

    if last_date and last_date < DOWNLOADED:
        w(f"**The repository was last modified {last_date.isoformat()}, "
          f"{(DOWNLOADED - last_date).days} days before we downloaded it, and has "
          f"not changed since.** The revision we hold is therefore `{sha}`.\n")
        w("**This is an inference, not a log entry.** It would be wrong if the "
          "repository had been changed and then reverted between those dates, "
          "which `lastModified` alone cannot rule out. Recorded as recovered "
          "rather than as captured at download time.\n")
    else:
        w(f"**The repository has been modified since our download** "
          f"({last} against {DOWNLOADED.isoformat()}). The current head `{sha}` "
          f"is therefore **not** necessarily the revision we hold, and this gap "
          f"cannot be closed this way.\n")

    w("## Corroboration: the file list\n")
    w(f"The endpoint lists **{len(data_files)}** data files. We hold "
      f"**{len(ours)}**, per the checksum table in `PROVENANCE.md`.\n")
    missing = sorted(set(data_files) - set(ours))
    extra = sorted(set(ours) - set(data_files))
    if not missing and not extra:
        w("**Every filename matches.** That is consistent with, though not proof "
          "of, the same revision.\n")
    else:
        if missing:
            w(f"In the repository but not in our manifest: {', '.join(missing)}\n")
        if extra:
            w(f"In our manifest but not in the repository: {', '.join(extra)}\n")
        w("A filename mismatch means the repository has changed shape since our "
          "download and the inference above should not be relied on.\n")

    w("## What is still not established\n")
    w("File-level integrity against the remote. We hold SHA256 checksums of all "
      "eleven inputs, but the endpoint publishes no checksums to compare them "
      "with, and re-downloading 79 GB of gated data to verify a provenance "
      "footnote is not a proportionate use of the challenge's bandwidth or "
      "ours. The checksums remain useful for detecting local corruption, which "
      "is what they were recorded for.\n")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
